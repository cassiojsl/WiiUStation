#!/usr/bin/env python3
"""Build source/lang_<xx>.h from the translations in this folder.

keys.txt   one English text per line, exactly as written in the C source
           (escapes kept). Line N (from 0) is text number N.
pt.py      Portuguese, as a dict { English: Portuguese }.
<xx>.txt   other languages, one "N|translation" per line. A missing number
           falls back to English.

Checks that every translation keeps the %d / %s placeholders of the English.
"""
import os, re, sys

HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(HERE, "..", "..", "source")
keys = open(os.path.join(HERE, "keys.txt"), encoding="utf-8").read().split("\n")
fmt = re.compile(r"%[0-9.]*[ds]")
bad = 0

def cstr(s):
    # texts are already C-escaped where they need it (\" and \x..)
    return s.replace('"', '\\"') if '\\"' not in s else s

def write(lang, pairs):
    global bad
    out = ["/* English -> %s. Generated by tools/lang/build.py: edit the files there. */" % lang]
    for en, tr in pairs:
        if fmt.findall(en) != fmt.findall(tr):
            print("%s: placeholders differ: %r -> %r" % (lang, en, tr)); bad += 1
        if en != tr:
            out.append('{ "%s", "%s" },' % (cstr(en), cstr(tr)))
    open(os.path.join(SRC, "lang_%s.h" % lang), "w", encoding="utf-8").write("\n".join(out) + "\n")
    print(lang, len(out) - 1)

# Portuguese
src = open(os.path.join(HERE, "pt.py"), encoding="utf-8").read()
src = src[:src.index("import sys, re")]
ns = {}
exec(src, ns)
write("pt", sorted(ns["PT"].items()))

for f in sorted(os.listdir(HERE)):
    if not f.endswith(".txt") or f == "keys.txt":
        continue
    pairs = []
    for ln in open(os.path.join(HERE, f), encoding="utf-8").read().split("\n"):
        if not ln.strip():
            continue
        n, t = ln.split("|", 1)
        pairs.append((keys[int(n)], t))
    write(f[:-4], pairs)
sys.exit(1 if bad else 0)
